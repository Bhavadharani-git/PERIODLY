[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)]
    [string]$ApiBaseUrl
)

$ErrorActionPreference = 'Stop'

try {
    $uri = [System.Uri]::new($ApiBaseUrl)
} catch {
    throw 'ApiBaseUrl must be a valid absolute HTTPS URL ending in /api.'
}

if ($uri.Scheme -ne 'https' -or -not $uri.Host -or $uri.UserInfo -or $uri.Query -or $uri.Fragment) {
    throw 'ApiBaseUrl must be an HTTPS URL without credentials, query strings, or fragments.'
}
if ($uri.AbsolutePath.TrimEnd('/') -notmatch '/api$') {
    throw 'ApiBaseUrl must end with /api, for example https://periodly.example.com/api.'
}

$mobileRoot = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$repoRoot = (Resolve-Path (Join-Path $mobileRoot '..')).Path
$sourceDir = Join-Path $repoRoot 'frontend'
$webDir = Join-Path $mobileRoot 'www'

if (-not (Test-Path (Join-Path $sourceDir 'index.html'))) {
    throw "Could not find frontend/index.html at: $sourceDir"
}

if (Test-Path $webDir) {
    Remove-Item -LiteralPath $webDir -Recurse -Force
}
New-Item -ItemType Directory -Path $webDir -Force | Out-Null
Copy-Item -Path (Join-Path $sourceDir '*') -Destination $webDir -Recurse -Force

$apiUrl = $uri.GetLeftPart([System.UriPartial]::Path).TrimEnd('/')
$configContent = @"
// Generated by mobile/scripts/Prepare-Mobile.ps1.
// This is a public API endpoint, NOT a secret. Never put PERIODLY_API_KEY here.
window.PERIODLY_CONFIG = {
  API_BASE_URL: "$apiUrl"
};
"@
Set-Content -LiteralPath (Join-Path $webDir 'config.js') -Value $configContent -Encoding utf8

Write-Host ''
Write-Host 'PERIODLY mobile web assets prepared.' -ForegroundColor Green
Write-Host "Web assets: $webDir"
Write-Host "API endpoint: $apiUrl"
Write-Host 'No administrator key was written to the mobile app.' -ForegroundColor Green
Write-Host ''
